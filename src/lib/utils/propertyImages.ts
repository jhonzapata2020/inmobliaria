/**
 * Simple string hash to deterministically choose an image index
 */
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Detects whether an existing image URL is the generic placeholder toy house
 */
export function isGenericPlaceholder(url?: string): boolean {
  if (!url) return true;
  return (
    url.includes('photo-1560518883-ce09059eeffa') ||
    url.includes('placeholder') ||
    url.trim() === ''
  );
}

/**
 * Returns a high-render list of appropriate images for a property
 */
export function getAppropriatePropertyImages(property: {
  id?: string;
  code?: string;
  title?: string;
  description?: string;
  assetType?: string;
  municipality?: string;
  department?: string;
  images?: string[];
  featuredImage?: string;
}): string[] {
  // If property already has non-generic custom images, return them
  const validExisting = (property.images || []).filter((img) => !isGenericPlaceholder(img));
  if (validExisting.length > 0) {
    return validExisting;
  }

  const code = property.code || property.id || 'DAR-PROP-001';
  const h = hashString(code);

  const assetType = (property.assetType || '').toLowerCase();
  const title = (property.title || '').toLowerCase();
  const desc = (property.description || '').toLowerCase();
  const muni = (property.municipality || '').toLowerCase();

  const isPlatanera =
    title.includes('platano') ||
    title.includes('plátano') ||
    title.includes('banano') ||
    desc.includes('platano') ||
    desc.includes('plátano') ||
    desc.includes('banano') ||
    muni.includes('turbo') ||
    muni.includes('apartado') ||
    muni.includes('apartadó') ||
    muni.includes('carepa') ||
    muni.includes('chigorodo') ||
    muni.includes('chigorodó') ||
    muni.includes('necocli') ||
    muni.includes('necoclí');

  let pool: string[];

  if (assetType.includes('finca')) {
    if (isPlatanera && h % 2 === 0) {
      pool = PLATANERA_BANANERA_IMAGES;
    } else if (h % 3 === 0) {
      pool = FINCA_CAMPESTRE_IMAGES;
    } else {
      pool = FINCA_GANADERA_IMAGES;
    }
  } else if (assetType.includes('lote') || assetType.includes('terreno')) {
    pool = LOTE_TERRENO_IMAGES;
  } else if (assetType.includes('casa')) {
    pool = CASA_IMAGES;
  } else if (assetType.includes('apartamento') || assetType.includes('apto')) {
    pool = APARTAMENTO_IMAGES;
  } else if (assetType.includes('bodega') || assetType.includes('local') || assetType.includes('edificio') || assetType.includes('oficina')) {
    pool = BODEGA_LOCAL_EDIFICIO_IMAGES;
  } else if (assetType.includes('parqueadero') || assetType.includes('garaje')) {
    pool = PARQUEADERO_IMAGES;
  } else {
    pool = isPlatanera ? PLATANERA_BANANERA_IMAGES : FINCA_GANADERA_IMAGES;
  }

  // Select 3 deterministic images from the pool
  const img1 = pool[h % pool.length];
  const img2 = pool[(h + 1) % pool.length];
  const img3 = pool[(h + 2) % pool.length];

  return [img1, img2, img3];
}
